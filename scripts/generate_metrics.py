"""Regenerates METRICS.md from the committed evaluation scripts.

    python scripts/generate_metrics.py            # write METRICS.md
    python scripts/generate_metrics.py --check    # fail if it drifted (CI)

Every measured number in METRICS.md comes from a committed script; README/CHANGELOG link here
instead of carrying hand-maintained figures.
"""

from __future__ import annotations

import argparse
import difflib
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PINNED = {
    "requests": ("https://github.com/psf/requests.git", "3c7baaa05ab4aa49cc819ce3a819d260de19c157"),
    "click": ("https://github.com/pallets/click.git", "2247b35ea1c47c727d7a06e51fa280e12a863ff6"),
}
SCALE_FILES = 5000


def run_json(*args: str) -> dict:
    completed = subprocess.run(
        [sys.executable, *args], cwd=ROOT, capture_output=True, text=True, check=False
    )
    if completed.returncode != 0:
        raise SystemExit(f"command failed: {' '.join(args)}\n{completed.stderr[-2000:]}")
    return json.loads(completed.stdout)


def ensure_repo(name: str, repos_dir: Path) -> Path:
    target = repos_dir / name
    url, sha = PINNED[name]
    if not target.exists():
        repos_dir.mkdir(parents=True, exist_ok=True)
        subprocess.run(["git", "clone", "-q", url, str(target)], check=True)
    head = subprocess.run(
        ["git", "-C", str(target), "rev-parse", "HEAD"], capture_output=True, text=True
    ).stdout.strip()
    if head != sha:
        subprocess.run(["git", "-C", str(target), "fetch", "-q", "origin", sha], check=False)
        subprocess.run(["git", "-C", str(target), "checkout", "-q", sha], check=True)
    return target


def fmt(value: float, digits: int = 1) -> str:
    return f"{value * 100:.{digits}f}%"


def render(repos_dir: Path) -> str:
    precision = {}
    recall = {}
    for name in PINNED:
        repo = ensure_repo(name, repos_dir)
        precision[name] = run_json(
            "benchmarks/edge_eval/precision.py", str(repo), "100", "--json"
        )
        recall[name] = run_json("benchmarks/edge_eval/recall.py", str(repo), "150", "--json")
    benchmark = run_json("benchmarks/token_bench.py", "--json")
    scale = run_json("benchmarks/scale/scale_bench.py", "--files", str(SCALE_FILES), "--json")

    lines: list[str] = [
        "# Generated metrics",
        "",
        "<!-- Generated by `python scripts/generate_metrics.py`. Do not edit by hand. -->",
        "",
        "Pinned inputs: "
        + ", ".join(f"{name} `{sha[:7]}`" for name, (_, sha) in PINNED.items())
        + ". Statistical intervals are 95% Wilson score intervals.",
        "",
        "## Edge precision (100 random call edges, seed 42)",
        "",
        "| Repo | Supported | Precision | Strict (direct) |",
        "|---|---:|---:|---:|",
    ]
    for name, data in precision.items():
        low, high = data["precision_ci95"]
        lines.append(
            f"| `{name}` | {data['canonical']}/{data['sampled']} | "
            f"{fmt(data['precision'])} (95% CI {fmt(low)}–{fmt(high)}) | "
            f"{data['strict']}/{data['sampled']} |"
        )
    lines += [
        "",
        "Strict counts require Jedi to land on the definition itself; the precision column also "
        "accepts re-export hops the engine resolves.",
        "",
        "## Conditional recall (150 call sites, seed 7)",
        "",
        "| Repo | Found / resolvable | Recall | Unresolved by Jedi |",
        "|---|---:|---:|---:|",
    ]
    for name, data in recall.items():
        low, high = data["recall_ci95"]
        lines.append(
            f"| `{name}` | {data['tool_edges_present']}/{data['jedi_project_targets']} | "
            f"{fmt(data['recall'])} (95% CI {fmt(low)}–{fmt(high)}) | "
            f"{data['unresolved_by_jedi']} |"
        )
    lines += [
        "",
        "Recall is conditional on Jedi resolving the call site to a project symbol; unconditional "
        "recall (hand-labelled true targets) is a Stage 1 deliverable and is not reported here.",
        "",
        "## Synthetic token benchmark (hops=2)",
        "",
        "| Target | Touched files | Repo | Slice | Saved vs files |",
        "|---|---:|---:|---:|---:|",
    ]
    for row in benchmark["slices"]:
        lines.append(
            f"| `{row['qualified_name']}` | {row['touched_files_tokens']} | "
            f"{row['full_repo_tokens']} | {row['slice_tokens']} | "
            f"{row['saved_vs_files_pct']}% |"
        )
    lines += [
        "",
        "Latency is excluded here because it is machine-dependent; run "
        "`benchmarks/scale/scale_bench.py` for timings.",
        "",
        f"## Scale ({SCALE_FILES} generated files, seed 42)",
        "",
        "| Files | Symbols | Edges |",
        "|---:|---:|---:|",
        f"| {scale['files']} | {scale['symbols']} | {scale['edges']} |",
        "",
        "Larger runs: `python benchmarks/scale/scale_bench.py --files 50000 --json`.",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--repos-dir", type=Path, default=Path("/tmp/eval-repos"))
    args = parser.parse_args()

    rendered = render(args.repos_dir)
    target = ROOT / "METRICS.md"
    if args.check:
        current = target.read_text(encoding="utf-8") if target.exists() else ""
        if current != rendered:
            diff = difflib.unified_diff(
                current.splitlines(), rendered.splitlines(), fromfile="METRICS.md", lineterm=""
            )
            print("\n".join(list(diff)[:200]))
            raise SystemExit("METRICS.md is stale; run python scripts/generate_metrics.py")
        print("METRICS.md is up to date")
        return
    target.write_text(rendered, encoding="utf-8")
    print(f"wrote {target}")


if __name__ == "__main__":
    main()
